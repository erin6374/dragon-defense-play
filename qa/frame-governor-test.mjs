// Deterministic governor regression; synthetic dt is NOT physical Windows FPS.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {AdaptiveFramebuffer} from '../src/rendering/frame-governor.js';
const game=readFileSync(new URL('../src/game.js',import.meta.url),'utf8');
assert.ok(game.includes('active&&!paused&&!document.hidden&&document.hasFocus()'),'foreground-only render pressure gate missing');
assert.ok(game.includes('adaptiveResolution:+adaptiveResolution.toFixed(2),adaptiveAdjustments'),'Windows heartbeat must expose framebuffer recovery state');
const g=new AdaptiveFramebuffer();
assert.equal(g.sample(3.2,true),false,'one long frame must not change quality');
assert.equal(g.sample(.016,true),false,'healthy frame clears isolated-stall streak');
for(let i=0;i<2;i++)assert.equal(g.sample(3.2,true),false);
assert.equal(g.sample(3.2,true),true,'three consecutive slideshow frames lower resolution');
assert.equal(g.scale,.88);assert.equal(g.adjustments,1);
for(let i=0;i<4;i++)assert.equal(g.sample(3.2,true),false,'cooldown protects from repeated resizes');
assert.equal(g.sample(3.2,true),true,'persistent slideshow can lower resolution again');
assert.equal(g.scale,.76);
g.reset();
for(let i=0;i<2;i++)g.sample(.4,true);
g.sample(.4,false);
assert.equal(g.sample(.4,true),false,'hidden/unfocused frames must not contribute');
assert.equal(g.sample(11,true),false,'suspended tab gap ignored');
assert.equal(g.sample(.4,true),false);
assert.equal(g.sample(.4,true),false);
assert.equal(g.sample(.4,true),true);
assert.equal(g.scale,.88);
g.reset();
for(let i=0;i<120;i++)assert.equal(g.sample(1/60,true),false,'60fps must not downscale');
assert.equal(g.scale,1);
g.reset();
for(let i=0;i<69;i++)assert.equal(g.sample(.04,true),false);
assert.equal(g.sample(.04,true),true,'ordinary low-fps path retained');
assert.equal(g.scale,.88);
console.log('RC58 sustained-slideshow framebuffer escape hatch, cooldown, focus, healthy and ordinary-window controls PASS');
